// ─────────────────────────────────────────────

export class MessagePaginationQueryDto {
  @ApiPropertyOptional({
    description: 'Number of messages to return (1-100)',
    default: 20,
  })
  @IsOptional()
  @IsInt()
  @Min(1)
  @Max(100)
  @Type(() => Number)
  limit?: number = 20;

  @ApiPropertyOptional({
    description: 'Base64-encoded cursor for pagination',
  })
  @IsOptional()
  @IsString()
  cursor?: string;
}

