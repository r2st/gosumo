import {
  IsString,
  IsUUID,
  IsEnum,
  IsOptional,
  IsObject,
  IsBoolean,
  IsNumber,
  IsInt,
  IsNotEmpty,
  IsDateString,
  Min,
  Max,
} from 'class-validator';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import { ChannelType, MessageStatus, MessageDirection } from '@gosumo/shared';

// ─────────────────────────────────────────────
// StoreInboundMessageDto
// ─────────────────────────────────────────────

export class StoreInboundMessageDto {
  @ApiProperty({ description: 'Conversation UUID' })
  @IsUUID()
  conversationId!: string;

  @ApiProperty({ description: 'Channel account UUID' })
  @IsUUID()
  channelAccountId!: string;

  @ApiProperty({ enum: ChannelType, description: 'Channel type' })
  @IsEnum(ChannelType)
  channel!: ChannelType;

  @ApiProperty({ description: 'Channel-assigned external message ID' })
  @IsString()
  externalId!: string;

  @ApiProperty({ description: 'Sender type: CLIENT or SYSTEM' })
  @IsString()
  senderType!: string;

  @ApiPropertyOptional({ description: 'Sender UUID (client_id or system actor)' })
  @IsOptional()
  @IsUUID()
  senderId?: string;

  @ApiProperty({ description: 'Message content payload (JSON)' })
  @IsObject()
  content!: Record<string, unknown>;

  @ApiPropertyOptional({ description: 'Extracted text content for search' })
  @IsOptional()
  @IsString()
  textContent?: string;

  @ApiPropertyOptional({ description: 'Additional metadata' })
  @IsOptional()
  @IsObject()
  metadata?: Record<string, unknown>;
}

